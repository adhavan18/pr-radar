"""Regenerate docs/QUERIES.md from the Cypher in the code.

    python -m prgraph.gendocs
"""
from pathlib import Path

from .agent.memory import MEMORY
from .algos import ALGOS
from .ingest import LOAD
from .queries import DEFAULTS, DOCS, QUERIES

OUT = Path(__file__).resolve().parent.parent / "docs" / "QUERIES.md"


def _block(title: str, cypher: str, desc: str | None = None) -> list[str]:
    out = [f"### {title}", ""]
    if desc:
        out += [desc, ""]
    return out + ["```cypher", cypher.strip(), "```", ""]


def render() -> str:
    defaults = ", ".join(f"{k}={v}" for k, v in DEFAULTS.items())
    lines = ["# Cypher queries", "",
             "Generated by `python -m prgraph.gendocs` from `prgraph/queries.py`, `prgraph/algos.py`, "
             "`prgraph/agent/memory.py` and `prgraph/ingest.py`. Ids: PR/Issue `owner/repo#N`, "
             f"File `owner/repo:path`, Repo `owner/repo`. Defaults: {defaults}.", "",
             "## Question queries", ""]
    for name, q in QUERIES.items():
        lines += _block(name, q, DOCS.get(name))
    lines += ["## Graph algorithms", ""]
    for name, q in ALGOS.items():
        lines += _block(name, q)
    lines += ["## Agent memory", ""]
    for name, q in MEMORY.items():
        lines += _block(name, q)
    lines += ["## Ingestion (batched UNWIND, idempotent MERGE)", ""]
    for key, q in LOAD:
        lines += _block(f"load {key}", q)
    return "\n".join(lines).rstrip() + "\n"


def main():
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
